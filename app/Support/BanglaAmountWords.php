    public static function integer(int $number): string
    {
        if ($number < 0) { return 'ঋণাত্মক '.self::integer(abs($number)); }
        if ($number < 100) { return self::SMALL[$number]; }
        foreach ([10000000 => 'কোটি', 100000 => 'লাখ', 1000 => 'হাজার', 100 => 'শত'] as $unit => $label) {
            if ($number >= $unit) {
                return self::integer(intdiv($number, $unit)).' '.$label
                    .($number % $unit ? ' '.self::integer($number % $unit) : '');
            }
        }
        return '';
    }

    public static function money($amount): string
    {
        // Display only: never feeds back into transaction calculations.
        $formatted = number_format(abs((float) $amount), 2, '.', '');
        [$whole, $fraction] = explode('.', $formatted);
        return ((float) $amount < 0 ? 'ঋণাত্মক ' : '').self::integer((int) $whole).' টাকা'
            .((int) $fraction ? ' '.self::integer((int) $fraction).' পয়সা' : '').' মাত্র';
    }
}
